export type DictKey = keyof typeof ru;
const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (key: DictKey) => string }>({ lang: "ru", setLang: () => {}, t: (k) => k });
export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");
  useEffect(() => { const saved = localStorage.getItem("lang") as Lang | null; if (saved === "ru" || saved === "en") setLangState(saved); }, []);
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem("lang", l); document.documentElement.lang = l; };
  const t = (key: DictKey): string => (lang === "ru" ? ru[key] : en[key] ?? ru[key]);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}
export function useLang() { return useContext(LangContext); }
